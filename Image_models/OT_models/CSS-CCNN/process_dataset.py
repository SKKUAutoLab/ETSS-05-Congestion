"""
process_dataset.py: Process the downloaded dataset for CrowdDataset.

1. parta: renames 'ground-truth' directories to 'ground_truth', the structure
   expected by CrowdDataset (see crowd_dataset.py docstring).
2. ucfqnrf: renames 'dataset/UCF-QNRF' to 'dataset/UCF-QNRF_ECCV18' (the path
   used by the training scripts) and organizes the raw layout (images and
   *_ann.mat files mixed in Train/ and Test/) into 'images' and 'ground_truth'
   subdirectories, the structure expected by CrowdDataset.
3. Generates 'assets/{name}_validation_files.npy', the validation split indices,
   with the same seed and sampling as stage1_main.py (stage_1=True).
4. Generates 'assets/{name}_xy_positions.log', the fixed validation crop
   positions required by CrowdDataset.val_get_data().

For every validation image (the split stored in 'assets/{name}_validation_files.npy',
regenerated by stage1_main.py with seed 11), a valid random crop position (y, x) is
sampled per pass, exactly like the sampling branch in CrowdDataset.val_get_data().
Line format: "sampling positions: {i}, {file_name}, {y}, {x}"

Usage:
    python process_dataset.py --dataset parta
"""

import argparse
import os
import random

import cv2
import numpy as np

NUM_PASSES = 5

# The xy positions log is consumed only by stage2_main++.py, which constructs
# CrowdDataset with gt_downscale_factor=8 and the default image_size_max=1024,
# and calls val_get_data() with batch size min(validation_set, 32).
VAL_BATCH_SIZE = 32
IMAGE_SIZE_MIN = 224
IMAGE_SIZE_MAX = 1024
IMAGE_SIZE_MULTIPLE = 8
IMAGE_CROP_SIZE = 224

DATASET_CONFIGS = {
    'parta': {
        'path': 'dataset/ST_partA/',
        'validation_set': 30,
    },
    'ucfqnrf': {
        'path': 'dataset/UCF-QNRF_ECCV18',
        'fallback_path': 'dataset/UCF-QNRF',
        'validation_set': 240,
    },
}


def compute_resized_shape(image_path, image_size_min, image_size_max, image_size_multiple):
    """
    Returns the (height, width) of an image after the resizing performed in
    CrowdDataset._read_image_and_gt_map().
    """
    image = cv2.imread(image_path)
    height, width = image.shape[0], image.shape[1]

    # setting minimum size
    if height < image_size_min or width < image_size_min:
        if height <= width:
            width = int((float(image_size_min * width) / height) + 0.5)
            height = image_size_min
        else:
            height = int((float(image_size_min * height) / width) + 0.5)
            width = image_size_min

    # setting maximum size
    if height > image_size_max or width > image_size_max:
        if height >= width:
            width = int((float(image_size_max * width) / height) + 0.5)
            height = image_size_max
        else:
            height = int((float(image_size_max * height) / width) + 0.5)
            width = image_size_max

    # make sizes multiple
    if height % image_size_multiple != 0:
        height = ((height // image_size_multiple) + 1) * image_size_multiple
    if width % image_size_multiple != 0:
        width = ((width // image_size_multiple) + 1) * image_size_multiple

    return height, width


def organize_ucfqnrf(config):
    """
    Renames the raw 'dataset/UCF-QNRF' download to the path used by the training
    scripts and moves each split's images and *_ann.mat files into 'images' and
    'ground_truth' subdirectories.
    """
    data_path = config['path']
    if not os.path.isdir(data_path) and os.path.isdir(config['fallback_path']):
        os.rename(config['fallback_path'], data_path)
        print('Renamed {} -> {}.'.format(config['fallback_path'], data_path))

    for split in ['Train', 'Test']:
        split_path = os.path.join(data_path, split)
        images_path = os.path.join(split_path, 'images')
        gt_path = os.path.join(split_path, 'ground_truth')
        loose_files = [f for f in sorted(os.listdir(split_path))
                       if os.path.isfile(os.path.join(split_path, f))]
        if not loose_files:
            continue
        os.makedirs(images_path, exist_ok=True)
        os.makedirs(gt_path, exist_ok=True)
        num_images, num_gts = 0, 0
        for f in loose_files:
            if f.endswith('_ann.mat'):
                os.rename(os.path.join(split_path, f), os.path.join(gt_path, f))
                num_gts += 1
            else:
                os.rename(os.path.join(split_path, f), os.path.join(images_path, f))
                num_images += 1
        print('Organized {}: {} images, {} ground truths.'.format(split_path,
                                                                  num_images, num_gts))


def rename_ground_truth_dirs(data_path, dataset_name):
    """
    Renames 'ground-truth' to 'ground_truth' in every split directory so the
    dataset matches the structure expected by CrowdDataset.
    """
    split_dirs = ['Train', 'Test'] if 'ucfqnrf' in dataset_name else ['train_data', 'test_data']
    for split in split_dirs:
        src = os.path.join(data_path, split, 'ground-truth')
        dst = os.path.join(data_path, split, 'ground_truth')
        if os.path.isdir(src) and not os.path.isdir(dst):
            os.rename(src, dst)
            print('Renamed {} -> {}.'.format(src, dst))


def main():
    parser = argparse.ArgumentParser(description='Generate validation xy positions log')
    parser.add_argument('--dataset', default='parta', choices=list(DATASET_CONFIGS.keys()),
                        help='dataset name')
    args = parser.parse_args()

    config = DATASET_CONFIGS[args.dataset]
    data_path = config['path']
    valid_set_size = config['validation_set']

    if 'ucfqnrf' in args.dataset:
        organize_ucfqnrf(config)
    else:
        rename_ground_truth_dirs(data_path, args.dataset)

    train_dir = 'Train' if 'ucfqnrf' in args.dataset else 'train_data'
    train_images_path = os.path.join(data_path, train_dir, 'images')
    files = [f for f in sorted(os.listdir(train_images_path))
             if os.path.isfile(os.path.join(train_images_path, f))]
    print('Found {} train images in {}.'.format(len(files), train_images_path))

    # -- Validation split: same seed and selection as stage1_main.py (stage_1=True)
    validation_files_path = 'assets/{}_validation_files.npy'.format(args.dataset)
    random.seed(11)
    files_selected = random.sample(range(0, len(files)), valid_set_size)
    np.save(validation_files_path, files_selected)
    print('Saved validation split ({} indices) to {}.'.format(len(files_selected),
                                                              validation_files_path))
    validation_files = [f for i, f in enumerate(files) if i in files_selected]
    print('{} validation images selected.'.format(len(validation_files)))

    # -- Validation images actually visited by val_get_data(): the file count is
    #    rounded down to a multiple of the batch size
    val_batch_size = min(valid_set_size, VAL_BATCH_SIZE)
    num_visited = len(validation_files) - (len(validation_files) % val_batch_size)
    visited_files = validation_files[: num_visited]

    # -- Resized shapes of the visited validation images
    shapes = {}
    for file_name in visited_files:
        shapes[file_name] = compute_resized_shape(
            os.path.join(train_images_path, file_name),
            IMAGE_SIZE_MIN, IMAGE_SIZE_MAX, IMAGE_SIZE_MULTIPLE)

    # -- Sample crop positions, same as the sampling branch of CrowdDataset.val_get_data()
    np.random.seed(11)
    log_path = 'assets/{}_xy_positions.log'.format(args.dataset)
    with open(log_path, 'w') as f:
        for _ in range(NUM_PASSES):
            for j, file_name in enumerate(visited_files):
                height, width = shapes[file_name]
                y, x = 0, 0
                if height > IMAGE_CROP_SIZE:
                    y = (np.random.randint(height - IMAGE_CROP_SIZE) // IMAGE_SIZE_MULTIPLE) \
                        * IMAGE_SIZE_MULTIPLE
                if width > IMAGE_CROP_SIZE:
                    x = (np.random.randint(width - IMAGE_CROP_SIZE) // IMAGE_SIZE_MULTIPLE) \
                        * IMAGE_SIZE_MULTIPLE
                f.write('sampling positions: {}, {}, {}, {}\n'.format(
                    j % val_batch_size, file_name, y, x))

    num_lines = NUM_PASSES * num_visited
    print('Wrote {} positions ({} passes x {} images) to {}.'.format(
        num_lines, NUM_PASSES, num_visited, log_path))


if __name__ == '__main__':
    main()
